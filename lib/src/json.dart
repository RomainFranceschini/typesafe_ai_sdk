/// JSON encoding and lenient response-body parsing.
library;

import 'dart:convert';

import 'errors.dart';

const int _maxOffendingValueInMessage = 100;

/// Decodes UTF-8 bytes straight into JSON values, without an intermediate
/// [String]. Strict about UTF-8; [parseBody] handles the failure.
final Converter<List<int>, Object?> _bodyDecoder = utf8.decoder.fuse(
  const JsonDecoder(),
);

/// Encodes JSON values straight to UTF-8 bytes, without an intermediate
/// [String]. Stateless between calls, so one instance is shared.
final JsonUtf8Encoder _bodyEncoder = JsonUtf8Encoder();

/// Parses a response body, preferring JSON and falling back to raw text.
///
/// Takes the raw bytes rather than `http.Response.body`, which would decode
/// them to a [String] only for the JSON parser to walk that string again.
/// Reading the bytes also sidesteps `Content-Type` entirely: the `body` getter
/// parses that header with `MediaType.parse` and throws a [FormatException] on
/// a value it cannot fully consume — for example duplicate `Content-Type`
/// response headers, which HTTP clients join with `, ` into a single invalid
/// value. The bytes are always read as UTF-8, which RFC 8259 requires of JSON,
/// so a `charset` in the header is deliberately ignored.
///
/// Returns `null` for an empty body or a body containing literal JSON `null`.
/// Callers cannot distinguish these two cases. JSON is attempted regardless of
/// the response's `Content-Type`, because proxies and servers do not reliably
/// set it, so the header is not consulted at all.
///
/// A body that is neither valid JSON nor valid UTF-8 is returned as text
/// decoded leniently, with malformed sequences replaced.
Object? parseBody(List<int> bytes) {
  if (bytes.isEmpty) return null;
  try {
    return _bodyDecoder.convert(bytes);
  } on FormatException {
    return utf8.decode(bytes, allowMalformed: true);
  }
}

/// Describes the value that could not be encoded, truncated for a message.
String _describeOffendingValue(Object? value) {
  final String rendered;
  try {
    rendered = value.toString();
  } on Object {
    // A broken `toString()` must not mask the encoding error being reported.
    return value.runtimeType.toString();
  }
  if (rendered.length > _maxOffendingValueInMessage) {
    return '${value.runtimeType} '
        '(${rendered.substring(0, _maxOffendingValueInMessage)}…)';
  }
  return '${value.runtimeType} ($rendered)';
}

/// Encodes [value] as UTF-8 JSON bytes, reporting failures against
/// [fieldPath].
///
/// Returns bytes rather than a [String] so the value is walked once: the
/// result goes straight onto the request as `bodyBytes`, where a string would
/// have been encoded to UTF-8 a second time.
///
/// Any object exposing a `toJson()` method is encodable, which is what lets
/// `state` accept classes generated by `json_serializable`, `freezed`, and
/// similar packages without this SDK depending on them.
///
/// A failure names the offending value rather than the field that held it:
/// a request body carries arbitrary caller objects in several places
/// (`state`, a question's `instructions`, a criteria description), and only
/// the value itself identifies which one went wrong.
List<int> encodeBody(Object? value, String fieldPath) {
  try {
    return _bodyEncoder.convert(value);
  } on JsonUnsupportedObjectError catch (error) {
    throw TypeSafeError(
      'Could not encode `$fieldPath` as JSON: '
      '${_describeOffendingValue(error.unsupportedObject)} is not '
      'JSON-encodable.',
    );
  } on NoSuchMethodError {
    throw TypeSafeError(
      'Could not encode `$fieldPath` as JSON: the value is not '
      'JSON-encodable.',
    );
  }
}
